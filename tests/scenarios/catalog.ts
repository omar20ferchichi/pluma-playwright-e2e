import fs from "fs";
import path from "path";

export const SCENARIO_CSV = path.resolve(__dirname, "../../docs/test_scenarios/pluma_test_scenarios.csv");

export type ScenarioStep = {
  scenarioId: string;
  domain: string;
  summary: string;
  step: number;
  testpointId: string;
  testpointClass: string;
  /** Constructor arguments; the CSV separates them with "|". */
  args: string[];
  expectedResult: string;
  /** "test" (default) or "teardown": teardown steps always run, even after a failure. */
  phase: "test" | "teardown";
};

export type Scenario = { id: string; domain: string; summary: string; steps: ScenarioStep[] };

/** Minimal RFC 4180 parser: quoted fields, doubled quotes, commas and newlines inside quotes. */
export function parseCsv(text: string): string[][] {
  const rows: string[][] = [];
  let row: string[] = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (ch === '"') quoted = false;
      else field += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ",") {
      row.push(field);
      field = "";
    } else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && text[i + 1] === "\n") i++;
      row.push(field);
      if (row.some((cell) => cell !== "")) rows.push(row);
      row = [];
      field = "";
    } else field += ch;
  }
  row.push(field);
  if (row.some((cell) => cell !== "")) rows.push(row);
  return rows;
}

export function loadSteps(file = SCENARIO_CSV): ScenarioStep[] {
  const [header, ...rows] = parseCsv(fs.readFileSync(file, "utf8"));
  const col = (name: string) => {
    const index = header.indexOf(name);
    if (index < 0) throw new Error(`${file} has no "${name}" column`);
    return index;
  };
  const c = {
    id: col("scenario_id"),
    domain: col("domain"),
    summary: col("summary"),
    step: col("step"),
    tp: col("testpoint_id"),
    cls: col("testpoint_class"),
    args: col("args"),
    expected: col("expected_result"),
    phase: header.indexOf("phase"), // optional column
  };
  return rows.map((r) => {
    const phase = (c.phase >= 0 ? r[c.phase] ?? "" : "").trim() || "test";
    if (phase !== "test" && phase !== "teardown") throw new Error(`${r[c.id]} step ${r[c.step]}: unknown phase "${phase}"`);
    return {
      scenarioId: r[c.id].trim(),
      domain: r[c.domain].trim(),
      summary: r[c.summary].trim(),
      step: Number(r[c.step]),
      testpointId: r[c.tp].trim(),
      testpointClass: r[c.cls].trim(),
      args: r[c.args] ? r[c.args].split("|").map((a) => a.trim()) : [],
      expectedResult: r[c.expected].trim(),
      phase,
    };
  });
}

export function loadScenarios(file = SCENARIO_CSV): Scenario[] {
  const byId = new Map<string, Scenario>();
  for (const step of loadSteps(file)) {
    let scenario = byId.get(step.scenarioId);
    if (!scenario) {
      scenario = { id: step.scenarioId, domain: step.domain, summary: step.summary, steps: [] };
      byId.set(step.scenarioId, scenario);
    }
    scenario.steps.push(step);
  }
  for (const scenario of byId.values()) scenario.steps.sort((a, b) => a.step - b.step);
  return [...byId.values()];
}

/** The spec source for one scenario. Pure function so the framework tests can check specs are up to date. */
export function renderSpec(scenario: Scenario): string {
  const classes = [...new Set(scenario.steps.map((s) => s.testpointClass))].sort();
  const render = (steps: ScenarioStep[], indent: string) =>
    steps
      .map((s) => {
        const args = s.args.map((a) => JSON.stringify(a)).join(", ");
        return `${indent}new ${s.testpointClass}(${args}), // ${s.step}. ${s.testpointId}: ${s.expectedResult}`;
      })
      .join("\n");
  const main = scenario.steps.filter((s) => s.phase === "test");
  const teardown = scenario.steps.filter((s) => s.phase === "teardown");
  const options = teardown.length ? `,\n      {\n        teardown: [\n${render(teardown, "          ")}\n        ],\n      },\n    ` : "";
  const call = teardown.length
    ? `    await runTestPoints(\n      loggedInPage,\n      [\n${render(main, "        ")}\n      ]${options});`
    : `    await runTestPoints(loggedInPage, [\n${render(main, "      ")}\n    ]);`;
  const timeout = teardown.length ? `    test.setTimeout(4 * 60 * 1000);\n` : "";
  return `// GENERATED by scripts/split-scenarios.ts from docs/test_scenarios/pluma_test_scenarios.csv. Do not edit by hand.
import { test } from "../../src/fixtures/auth";
import { runTestPoints } from "../runTestPoints";
import { ${classes.join(", ")} } from "../../src/catalog";

test.describe(${JSON.stringify(scenario.domain)}, () => {
  test(${JSON.stringify(`${scenario.id} ${scenario.summary}`)}, async ({ loggedInPage }) => {
${timeout}${call}
  });
});
`;
}
